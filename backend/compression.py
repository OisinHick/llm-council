"""Token and Context Compression Layer for LLM Council.

This module provides context optimization and token compression services to reduce prompt token
overhead, lower API spend, and maximize effective context window utilization without compromising
semantic accuracy or code structure.

Supported Compression Strategies:
    1. Headroom AI SDK (`headroom`):
       - Advanced content-aware semantic and structural compression.
       - Leverages SmartCrusher algorithms for JSON payloads and AST-aware code compression.
       - Automatically maps OpenRouter model names to supported Headroom model targets.
    2. Heuristic Pruning (`heuristic`):
       - Deterministic rule-based text compaction.
       - Collapses excessive vertical whitespace (3+ newlines -> 2 newlines).
       - Collapses horizontal spaces and indentation runs (3+ spaces -> single space).
       - Normalizes extended markdown horizontal rules and ASCII delimiters.
       - Compacts multi-line JSON structures into single-line minified JSON.
       - Strips conversational preambles ("Sure! I can help with...", "As an AI language model...").
    3. Adaptive Hybrid (`adaptive`):
       - Multi-stage pipeline: runs fast Heuristic cleaning first, followed by Headroom semantic compression.
    4. Safety Invariant:
       - If any compression strategy results in an output larger than the original text
         (e.g., token expansion), the compression engine automatically discards the compressed
         result and keeps the original uncompressed messages.
"""

from __future__ import annotations

import json
import logging
import re
from dataclasses import dataclass, field
from typing import Any

logger = logging.getLogger(__name__)

# ==============================================================================
# Precompiled Regex Patterns for Heuristic Text Optimization
# ==============================================================================

# Compacts 4 or more consecutive delimiter characters (e.g. "====", "----", "####", "~~~~") into standard markdown "---"
_RE_DELIMITERS = re.compile(r"([=\-_*#~]{4,})")

# Collapses 3 or more consecutive newlines down to standard paragraph spacing (\n\n)
_RE_NEWLINES = re.compile(r"\n{3,}")

# Collapses 3 or more consecutive non-newline whitespace characters down to a single space
_RE_SPACES = re.compile(r"[^\S\r\n]{3,}")

# Identifies and strips common conversational boilerplate preambles generated by LLMs
_RE_PREAMBLES = [
    re.compile(
        r"^(Sure|Certainly|Of course)!\s*(I would be happy to|Here is|I can help with).*?:\s*\n*",
        re.IGNORECASE,
    ),
    re.compile(r"^As an AI language model,\s*", re.IGNORECASE),
]

# Matches simple single-level JSON dictionary blocks for compact minification
_RE_JSON_BLOCK = re.compile(r"\{[^{}]*:[^{}]*\}", re.DOTALL)


def _compact_json_match(match: re.Match) -> str:
    """Helper regex substitution callback to parse and minify JSON object snippets.

    Attempts to parse the matched text as valid JSON. If successful, re-serializes
    it with compact separators (`,`, `:`) removing unnecessary internal whitespace.
    If parsing fails, returns the original matched text unchanged.

    Args:
        match: Regex match object containing the JSON candidate text.

    Returns:
        str: Minified JSON string if valid JSON, or the original text.
    """
    raw_json = match.group(0)
    try:
        parsed = json.loads(raw_json)
        return json.dumps(parsed, separators=(",", ":"))
    except Exception:
        return raw_json


def _fallback_heuristic_with_estimates(
    messages: list[dict[str, Any]],
) -> tuple[list[dict[str, Any]], int, int, list[str]]:
    """Helper to apply heuristic compression and calculate before/after token counts.

    Used when Headroom is unavailable or encounters an error during execution.

    Args:
        messages: Original list of message dictionaries.

    Returns:
        tuple: (compressed_messages, tokens_before, tokens_after, transforms_applied).
    """
    comp_msgs, transforms = compress_with_heuristic(messages)
    t_before = estimate_messages_tokens(messages)
    t_after = estimate_messages_tokens(comp_msgs)
    return comp_msgs, t_before, t_after, transforms


# Attempt to load OpenAI's tiktoken for accurate BPE token counting; fallback to None
try:
    import tiktoken

    _TIKTOKEN_ENC = tiktoken.get_encoding("cl100k_base")
except Exception:
    _TIKTOKEN_ENC = None

# Attempt to load Headroom AI SDK; track availability flag
try:
    import headroom

    _HAS_HEADROOM = True
except ImportError:
    headroom = None
    _HAS_HEADROOM = False


@dataclass
class CompressionResult:
    """Structured report returned by the compression pipeline.

    Attributes:
        messages: The resulting message list (compressed or original).
        tokens_before: Estimated token count prior to compression.
        tokens_after: Estimated token count following compression.
        tokens_saved: Net prompt tokens saved (tokens_before - tokens_after).
        compression_ratio: Percentage of tokens eliminated (e.g., 0.25 for 25% reduction).
        algorithm: Name of the algorithm executed ('headroom', 'heuristic', 'adaptive', 'disabled').
        transforms_applied: List of specific transformations executed (e.g. 'collapse_spaces').
    """

    messages: list[dict[str, Any]]
    tokens_before: int
    tokens_after: int
    tokens_saved: int
    compression_ratio: float
    algorithm: str
    transforms_applied: list[str] = field(default_factory=list)


# Cumulative in-memory compression analytics
_COMPRESSION_STATS: dict[str, Any] = {
    "total_queries": 0,
    "tokens_before": 0,
    "tokens_after": 0,
    "tokens_saved": 0,
    "algorithm_counts": {},
}


def estimate_tokens(text: str | None) -> int:
    """Estimate token count for a text string using tiktoken BPE or a 4-character heuristic.

    Uses the OpenAI `cl100k_base` tokenizer encoding when available. If tiktoken is not installed
    or encoding encounters an exception, falls back to the standard industry heuristic of
    1 token ~= 4 UTF-8 characters.

    Args:
        text: Input text string to evaluate.

    Returns:
        int: Estimated token count (0 for empty or None text, minimum 1 for non-empty text).
    """
    if not text:
        return 0
    if _TIKTOKEN_ENC is not None:
        try:
            return len(_TIKTOKEN_ENC.encode(text))
        except Exception:
            pass
    return max(1, len(text) // 4)


def estimate_messages_tokens(messages: list[dict[str, Any]]) -> int:
    """Estimate total token consumption for a list of chat message dictionaries.

    Iterates through each message in `messages`, evaluating string or multi-part content
    blocks, and adds 3 tokens per message for chat markup/role overhead.

    Args:
        messages: List of chat message dicts containing 'role' and 'content'.

    Returns:
        int: Cumulative estimated token count across all messages.
    """
    total = 0
    for m in messages:
        content = m.get("content") or ""
        if isinstance(content, list):
            for part in content:
                if isinstance(part, dict) and "text" in part:
                    total += estimate_tokens(str(part["text"]))
                elif isinstance(part, str):
                    total += estimate_tokens(part)
        else:
            total += estimate_tokens(str(content))
        total += 3  # message overhead
    return total


def map_model_for_headroom(model: str | None) -> str:
    """Map OpenRouter model identifier strings to supported Headroom AI target model identifiers.

    Headroom optimizes prompts targeting specific model families (e.g., 'gpt-4o', 'claude-3-5-sonnet',
    'gemini-1.5-pro'). This function maps diverse OpenRouter model slugs to the closest Headroom profile.

    Args:
        model: OpenRouter model identifier (e.g. 'google/gemini-2.5-flash').

    Returns:
        str: Headroom model identifier ('gpt-4o', 'claude-3-5-sonnet', or 'gemini-1.5-pro').
    """
    if not model:
        return "gpt-4o"
    m_lower = model.lower()
    if "gpt" in m_lower or "o1" in m_lower or "o3" in m_lower:
        return "gpt-4o"
    if "claude" in m_lower:
        return "claude-3-5-sonnet"
    if "gemini" in m_lower:
        return "gemini-1.5-pro"
    return "gpt-4o"


def compress_heuristic_text(text: str) -> tuple[str, list[str]]:
    """Apply deterministic heuristic text optimization rules to a single text string.

    Rules applied:
      1. Short-circuit: strings shorter than 40 characters are left unmodified.
      2. Delimiter normalization: compresses long runs of repeated horizontal symbols to `---`.
      3. Newline compaction: replaces 3 or more consecutive newlines with `\n\n`.
      4. Whitespace compaction: collapses 3 or more spaces into a single space.
      5. Preamble removal: strips AI conversational intros ("Sure! Here is...").
      6. JSON minification: minifies formatting whitespace in candidate JSON blocks.

    Args:
        text: Raw string content from a prompt message.

    Returns:
        tuple[str, list[str]]: (optimized text string, list of transformation names applied).
    """
    if not text or len(text) < 40:
        return text, []

    transforms = []
    compressed = text

    # Compact long horizontal lines / delimiters
    if _RE_DELIMITERS.search(compressed):
        compressed = _RE_DELIMITERS.sub("---", compressed)
        transforms.append("compact_delimiters")

    # Collapse 3+ newlines to 2
    if "\n\n\n" in compressed:
        compressed = _RE_NEWLINES.sub("\n\n", compressed)
        transforms.append("collapse_newlines")

    # Collapse 3+ spaces to 1
    if "   " in compressed:
        compressed = _RE_SPACES.sub(" ", compressed)
        transforms.append("collapse_spaces")

    # Strip conversational preambles
    for p in _RE_PREAMBLES:
        if p.search(compressed):
            compressed = p.sub("", compressed)
            transforms.append("strip_preamble")

    # Compact multi-line JSON blocks
    if "{\n" in compressed and "}" in compressed:
        new_text = _RE_JSON_BLOCK.sub(_compact_json_match, compressed)
        if len(new_text) < len(compressed):
            compressed = new_text
            transforms.append("compact_json")

    return compressed, transforms


def compress_with_heuristic(
    messages: list[dict[str, Any]],
) -> tuple[list[dict[str, Any]], list[str]]:
    """Execute heuristic compression across all messages in a conversation array.

    Clones each message dictionary, applies `compress_heuristic_text` to its string content,
    and collects the distinct set of transformations applied across all messages.

    Args:
        messages: List of chat message dicts.

    Returns:
        tuple[list[dict[str, Any]], list[str]]:
            - New message list with compressed text content.
            - List of unique transformation names applied.
    """
    new_messages = []
    all_transforms = set()
    for m in messages:
        new_m = dict(m)
        content = m.get("content")
        if isinstance(content, str):
            comp_content, transforms = compress_heuristic_text(content)
            new_m["content"] = comp_content
            all_transforms.update(transforms)
        new_messages.append(new_m)
    return new_messages, list(all_transforms)


def compress_with_headroom(
    messages: list[dict[str, Any]], model: str = "gpt-4o"
) -> tuple[list[dict[str, Any]], int, int, list[str]]:
    """Compress a message list using the Headroom AI SDK.

    Calls `headroom.compress` targeting the mapped model architecture.
    If the `headroom` package is not installed or encounters an API error,
    it falls back to heuristic compression.

    Args:
        messages: List of chat messages to compress.
        model: OpenRouter or target model identifier string.

    Returns:
        tuple[list[dict[str, Any]], int, int, list[str]]:
            - Compressed messages list.
            - Tokens before compression.
            - Tokens after compression.
            - List of transformation names applied.
    """
    if not _HAS_HEADROOM:
        logger.warning("headroom package not installed, falling back to heuristic.")
        return _fallback_heuristic_with_estimates(messages)

    target_model = map_model_for_headroom(model)
    try:
        result = headroom.compress(
            messages=messages,
            model=target_model,
            compress_user_messages=True,
            optimize=True,
        )
        t_before = getattr(result, "tokens_before", None)
        if t_before is None:
            t_before = estimate_messages_tokens(messages)
        t_after = getattr(result, "tokens_after", None)
        if t_after is None:
            t_after = estimate_messages_tokens(result.messages)
        transforms = getattr(result, "transforms_applied", [])
        if not transforms:
            transforms = ["headroom_content_router"]
        return result.messages, t_before, t_after, transforms
    except Exception as e:
        logger.warning("Headroom compression error: %s; falling back to heuristic.", e)
        return _fallback_heuristic_with_estimates(messages)


def compress_messages(
    messages: list[dict[str, Any]],
    model: str = "gpt-4o",
    algorithm: str = "headroom",
    enabled: bool = True,
) -> CompressionResult:
    """Compress a message list using the requested algorithm and record cumulative metrics.

    Execution Pipeline:
      1. Checks if `enabled` is True; if False, returns early with algorithm="disabled".
      2. Estimates baseline token count before compression.
      3. Dispatches to selected algorithm:
         - "heuristic": Rule-based whitespace, preamble, and JSON minification.
         - "headroom": Headroom AI SmartCrusher & content optimization.
         - "adaptive": Hybrid heuristic pass followed by Headroom optimization.
      4. Safety Verification: If `tokens_after > tokens_before`, the compressed text is
         discarded and the original uncompressed messages are returned.
      5. Updates global cumulative compression statistics (`_COMPRESSION_STATS`).

    Args:
        messages: List of chat message dicts.
        model: Model identifier for model-specific compression tuning.
        algorithm: Compression algorithm ('headroom', 'heuristic', 'adaptive').
        enabled: Whether compression is enabled.

    Returns:
        CompressionResult: Complete compression report including messages, tokens, and ratio.
    """
    tokens_before = estimate_messages_tokens(messages)
    if not enabled:
        return CompressionResult(
            messages=messages,
            tokens_before=tokens_before,
            tokens_after=tokens_before,
            tokens_saved=0,
            compression_ratio=0.0,
            algorithm="disabled",
            transforms_applied=[],
        )

    algo = (algorithm or "headroom").lower()
    transforms_applied = []
    compressed_messages = messages
    tokens_after = tokens_before

    try:
        if algo == "heuristic":
            compressed_messages, transforms = compress_with_heuristic(messages)
            transforms_applied.extend(transforms)
            tokens_after = estimate_messages_tokens(compressed_messages)
        elif algo == "adaptive":
            h_msgs, h_transforms = compress_with_heuristic(messages)
            transforms_applied.extend(h_transforms)
            compressed_messages, _, t_after, hr_transforms = compress_with_headroom(
                h_msgs, model=model
            )
            transforms_applied.extend(hr_transforms)
            tokens_after = t_after
        else:  # headroom
            compressed_messages, _, tokens_after, hr_transforms = (
                compress_with_headroom(messages, model=model)
            )
            transforms_applied.extend(hr_transforms)
    except Exception as e:
        logger.exception("Unexpected error in compress_messages: %s", e)
        compressed_messages = messages
        tokens_after = tokens_before

    # If compression increased tokens, keep original
    if tokens_after > tokens_before:
        compressed_messages = messages
        tokens_after = tokens_before

    tokens_saved = max(0, tokens_before - tokens_after)
    ratio = round(tokens_saved / tokens_before, 4) if tokens_before > 0 else 0.0

    # Update cumulative statistics
    _COMPRESSION_STATS["total_queries"] += 1
    _COMPRESSION_STATS["tokens_before"] += tokens_before
    _COMPRESSION_STATS["tokens_after"] += tokens_after
    _COMPRESSION_STATS["tokens_saved"] += tokens_saved
    _COMPRESSION_STATS["algorithm_counts"][algo] = (
        _COMPRESSION_STATS["algorithm_counts"].get(algo, 0) + 1
    )

    return CompressionResult(
        messages=compressed_messages,
        tokens_before=tokens_before,
        tokens_after=tokens_after,
        tokens_saved=tokens_saved,
        compression_ratio=ratio,
        algorithm=algo,
        transforms_applied=list(dict.fromkeys(transforms_applied)),
    )


def get_compression_stats() -> dict[str, Any]:
    """Retrieve cumulative token compression metrics and estimated dollar savings.

    Calculates aggregate compression ratio, estimated monetary savings based on
    an average prompt rate ($0.50 per 1M tokens), and reports whether the Headroom
    package is available in the current environment.

    Returns:
        dict[str, Any]: Analytics dictionary containing:
            - "total_queries" (int): Number of compression operations evaluated.
            - "tokens_before" (int): Cumulative prompt tokens before compression.
            - "tokens_after" (int): Cumulative prompt tokens after compression.
            - "tokens_saved" (int): Total prompt tokens saved.
            - "compression_ratio" (float): Overall fractional savings.
            - "estimated_dollars_saved" (float): Estimated USD saved.
            - "algorithm_counts" (dict): Breakdown of runs per algorithm.
            - "headroom_available" (bool): Whether headroom is installed and importable.
    """
    total_before = _COMPRESSION_STATS["tokens_before"]
    total_saved = _COMPRESSION_STATS["tokens_saved"]
    ratio = round(total_saved / total_before, 4) if total_before > 0 else 0.0
    dollars_saved = round(total_saved * 0.0000005, 6)
    return {
        "total_queries": _COMPRESSION_STATS["total_queries"],
        "tokens_before": total_before,
        "tokens_after": _COMPRESSION_STATS["tokens_after"],
        "tokens_saved": total_saved,
        "compression_ratio": ratio,
        "estimated_dollars_saved": dollars_saved,
        "algorithm_counts": dict(_COMPRESSION_STATS["algorithm_counts"]),
        "headroom_available": _HAS_HEADROOM,
    }


def reset_compression_stats() -> None:
    """Reset all cumulative in-memory token compression statistics to zero.

    Clears total queries, token counters, and algorithm count dictionaries.
    Primarily used during unit and integration test teardown.
    """
    _COMPRESSION_STATS["total_queries"] = 0
    _COMPRESSION_STATS["tokens_before"] = 0
    _COMPRESSION_STATS["tokens_after"] = 0
    _COMPRESSION_STATS["tokens_saved"] = 0
    _COMPRESSION_STATS["algorithm_counts"].clear()
